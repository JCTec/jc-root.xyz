#!/usr/bin/env node
/* Applies the site's header and cache policy to Cloudflare.
 *
 * GitHub Pages sends no response headers of its own and offers no way to add
 * them, so everything SiteHeadersMiddleware used to apply is delivered at the
 * edge instead. That configuration lives outside this repository, where
 * nothing in CI can see it regress, so this script exists to make it
 * reproducible: the rules are generated from lib/headers.mjs and
 * lib/cache-policy.mjs, which stay the single source of truth.
 *
 * Usage:  node scripts/cloudflare-headers.mjs [--dry-run]
 * Env:    CLOUDFLARE_API_TOKEN   needs Zone → Transform Rules → Edit
 *         CLOUDFLARE_ZONE        defaults to jc-root.xyz
 *
 * Re-running is safe: it updates the ruleset it created rather than adding a
 * second one.
 */
import { cachePolicyForPath } from "../lib/cache-policy.mjs";
import { EDGE_HEADERS } from "../lib/headers.mjs";

const PHASE = "http_response_headers_transform";
const RULESET_NAME = "Site headers (jc-root.xyz)";
const zoneName = process.env.CLOUDFLARE_ZONE ?? "jc-root.xyz";
const token = process.env.CLOUDFLARE_API_TOKEN;
const dryRun = process.argv.includes("--dry-run");

const P = "http.request.uri.path";
const setHeaders = (headers) => ({
    action: "rewrite",
    action_parameters: {
        headers: Object.fromEntries(
            Object.entries(headers).map(([name, value]) => [name, { operation: "set", value }]),
        ),
    },
});
const cacheRule = (expression, samplePath, description) => ({
    ...setHeaders({ "Cache-Control": cachePolicyForPath(samplePath) }),
    expression,
    description,
    enabled: true,
});

/* Mutually exclusive by construction, so rule order cannot change the answer. */
export const rules = [
    {
        ...setHeaders(EDGE_HEADERS),
        expression: "true",
        description: "Security headers on every response",
        enabled: true,
    },
    cacheRule(
        `starts_with(${P}, "/vendor/") or starts_with(${P}, "/icons/") or ${P} == "/favicon.ico"`,
        "/vendor/x.css",
        "Vendored assets and icons: immutable for a year",
    ),
    cacheRule(
        `(ends_with(${P}, ".css") or ends_with(${P}, ".js") or ends_with(${P}, ".webmanifest"))`
            + ` and not starts_with(${P}, "/vendor/") and not starts_with(${P}, "/icons/")`,
        "/css/site.css",
        "Site CSS/JS: revalidate daily, keyed on ?v=",
    ),
    cacheRule(
        `${P} in {"/robots.txt" "/sitemap.xml" "/llms.txt"}`,
        "/robots.txt",
        "Discovery surfaces: an hour",
    ),
    cacheRule(
        `ends_with(${P}, "/") or ends_with(${P}, ".html")`,
        "/",
        "HTML is never publicly cached",
    ),
];

if (dryRun) {
    for (const rule of rules) {
        console.log(`- ${rule.description}`);
        console.log(`    when: ${rule.expression}`);
        for (const [name, { value }] of Object.entries(rule.action_parameters.headers)) {
            console.log(`    ${name}: ${value}`);
        }
    }
    process.exit(0);
}

if (!token) {
    console.error("CLOUDFLARE_API_TOKEN is not set.");
    process.exit(2);
}

async function cf(path, init = {}) {
    const res = await fetch(`https://api.cloudflare.com/client/v4${path}`, {
        ...init,
        headers: { Authorization: `Bearer ${token}`, "Content-Type": "application/json" },
    });
    const body = await res.json();
    if (!body.success) {
        const message = (body.errors ?? []).map((e) => e.message).join("; ");
        // The one failure worth naming: this is the permission people forget.
        const hint = /not authorized/i.test(message)
            ? "\n  The token needs Zone → Transform Rules → Edit on this zone."
            : "";
        throw new Error(`${path}: ${message || res.status}${hint}`);
    }
    return body.result;
}

const [zone] = await cf(`/zones?name=${encodeURIComponent(zoneName)}`);
if (!zone) throw new Error(`no zone named ${zoneName}`);

const existing = (await cf(`/zones/${zone.id}/rulesets`)).find((r) => r.phase === PHASE);
const payload = {
    name: RULESET_NAME,
    description:
        "What SiteHeadersMiddleware used to send. Generated by scripts/cloudflare-headers.mjs"
        + " from lib/headers.mjs and lib/cache-policy.mjs; change those first.",
    kind: "zone",
    phase: PHASE,
    rules,
};

const result = existing
    ? await cf(`/zones/${zone.id}/rulesets/${existing.id}`, {
        method: "PUT",
        body: JSON.stringify({ ...payload, id: existing.id }),
    })
    : await cf(`/zones/${zone.id}/rulesets`, { method: "POST", body: JSON.stringify(payload) });

console.log(`${existing ? "updated" : "created"} ruleset ${result.id} on ${zoneName}`);
for (const rule of result.rules ?? []) console.log(`  ✔ ${rule.description}`);
